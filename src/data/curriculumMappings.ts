export const getMappingsForTopic = (topicId: string): CurriculumTopicMapping[] => {
  return CURRICULUM_TOPIC_MAPPINGS.filter((m) => m.topicId === topicId);
};

export const getPrimaryMappingForTopic = (
  topicId: string,
  preferredBoard?: 'CBSE' | 'CISCE',
  preferredClass?: 6 | 7 | 8 | 9 | 10
): CurriculumTopicMapping | undefined => {
  const mappings = getMappingsForTopic(topicId);
  if (mappings.length === 0) return undefined;
  if (preferredBoard && preferredClass) {
    const match = mappings.find(
      (m) => m.boardCode === preferredBoard && m.classLevel === preferredClass
    );
    if (match) return match;
  }
  if (preferredBoard) {
    const match = mappings.find((m) => m.boardCode === preferredBoard);
    if (match) return match;
  }
  if (preferredClass) {
    const match = mappings.find((m) => m.classLevel === preferredClass);
    if (match) return match;
  }
  return mappings[0];
};

export const isTopicInCurriculum = (
  topicId: string,
  boardCode?: 'CBSE' | 'CISCE' | 'all',
  classLevel?: 6 | 7 | 8 | 9 | 10 | 'all'
): boolean => {
  if ((!boardCode || boardCode === 'all') && (!classLevel || classLevel === 'all')) {
    return true;
  }
  const mappings = getMappingsForTopic(topicId);
  return mappings.some((m) => {
    const matchesBoard = !boardCode || boardCode === 'all' || m.boardCode === boardCode;
    const matchesClass = !classLevel || classLevel === 'all' || m.classLevel === classLevel;
    return matchesBoard && matchesClass;
  });
};

